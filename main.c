// Prayer Times for Nintendo Switch (homebrew .nro)
//
// Shows Fajr/Sunrise/Dhuhr/Asr/Maghrib/Isha for a huge built-in offline city
// database, any custom lat/lon you type in, or any place you search for by
// name online (Aladhan API). Everything about a location can be saved with
// a name for instant reuse, and the app remembers your last-used location
// and launches straight into it.
//
// Build with devkitPro (see README.md). Requires the following devkitPro
// pacman packages in addition to the base switch-dev group:
//   switch-curl switch-mbedtls switch-zlib switch-jansson
//
// Feature summary:
//   - Custom coordinates (typed in by hand)
//   - Named saved locations (custom coordinates OR searched addresses)
//   - Six calculation methods: ISNA, MWL, Umm Al-Qura, Karachi, Egyptian, Tehran
//   - Hanafi / Standard(Shafi) Asr
//   - High-latitude adjustment (Middle of Night / One-Seventh / Angle-Based)
//   - Automatic date & time from the console's own clock/timezone database
//   - Next-prayer countdown
//   - Monthly prayer timetable, scrollable, month-to-month
//   - Works fully offline; uses the live Aladhan API when available for the
//     freshest numbers, silently falling back to the offline calculator
//   - ~480 built-in offline cities, with heavy coverage of the Muslim world
//   - Type-to-filter, page jump (L/R) and letter jump (ZL/ZR) to navigate

