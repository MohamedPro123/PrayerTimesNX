// Computes which prayer is next given today's six HH:MM strings and the
// current local fractional hour. Returns 1 and fills *outName/*outMinutes
// if a next prayer could be determined (i.e. we know "now" for this
// location), else 0 (shown as "--" in the UI, e.g. for a plain address
// search with no timezone info yet).
static int computeNextPrayer(const PrayerResult *r, int haveNow, double nowFrac,
                              const char **outName, int *outMinutesRemaining) {
    if (!haveNow) return 0;
    static const char *names[6] = { "Fajr", "Sunrise", "Dhuhr", "Asr", "Maghrib", "Isha" };
    const char *times[6] = { r->fajr, r->sunrise, r->dhuhr, r->asr, r->maghrib, r->isha };
    double hours[6];
    for (int i = 0; i < 6; i++) {
        if (!parseHourMin(times[i], &hours[i])) return 0;
    }
    for (int i = 0; i < 6; i++) {
        if (hours[i] > nowFrac) {
            *outName = names[i];
            *outMinutesRemaining = (int)round((hours[i] - nowFrac) * 60.0);
            return 1;
        }
    }
    // Past Isha -- next prayer is tomorrow's Fajr.
    *outName = "Fajr";
    *outMinutesRemaining = (int)round((24.0 - nowFrac + hours[0]) * 60.0);
    return 1;
}

