// One line per saved location, pipe-delimited:
//   name|lat|lon|hasTz|tz|utcOffset
// Names are sanitized (no '|' or newline) when saving.
static int g_savedCount = 0;
static NamedLocation g_saved[MAX_SAVED_LOCATIONS];

static void sanitizeField(char *s) {
    for (char *p = s; *p; p++) {
        if (*p == '|' || *p == '\n' || *p == '\r') *p = ' ';
    }
}

static void loadSavedLocations(void) {
    g_savedCount = 0;
    FILE *f = fopen(LOCATIONS_PATH, "r");
    if (!f) return;
    char line[512];
    while (fgets(line, sizeof(line), f) && g_savedCount < MAX_SAVED_LOCATIONS) {
        char *nl = strchr(line, '\n'); if (nl) *nl = 0;
        if (line[0] == 0) continue;
        NamedLocation n;
        memset(&n, 0, sizeof(n));
        char *tok, *save = NULL;
        int field = 0;
        tok = strtok_r(line, "|", &save);
        while (tok) {
            switch (field) {
                case 0: snprintf(n.name, sizeof(n.name), "%s", tok); break;
                case 1: n.lat = atof(tok); break;
                case 2: n.lon = atof(tok); break;
                case 3: n.hasTz = atoi(tok); break;
                case 4: snprintf(n.tz, sizeof(n.tz), "%s", tok); break;
                case 5: n.utcOffset = atof(tok); break;
            }
            field++;
            tok = strtok_r(NULL, "|", &save);
        }
        if (field >= 6) g_saved[g_savedCount++] = n;
    }
    fclose(f);
}

static void writeSavedLocations(void) {
    ensureConfigDir();
    FILE *f = fopen(LOCATIONS_PATH, "w");
    if (!f) return;
    for (int i = 0; i < g_savedCount; i++) {
        NamedLocation *n = &g_saved[i];
        fprintf(f, "%s|%f|%f|%d|%s|%f\n", n->name, n->lat, n->lon, n->hasTz,
                n->hasTz ? n->tz : "-", n->utcOffset);
    }
    fclose(f);
}

// Adds or, if a saved location with the same name exists, overwrites it.
static void addOrUpdateSavedLocation(const NamedLocation *n) {
    for (int i = 0; i < g_savedCount; i++) {
        if (strcasecmp(g_saved[i].name, n->name) == 0) {
            g_saved[i] = *n;
            writeSavedLocations();
            return;
        }
    }
    if (g_savedCount < MAX_SAVED_LOCATIONS) {
        g_saved[g_savedCount++] = *n;
        writeSavedLocations();
    }
}

static void deleteSavedLocation(int index) {
    if (index < 0 || index >= g_savedCount) return;
    for (int i = index; i < g_savedCount - 1; i++) g_saved[i] = g_saved[i + 1];
    g_savedCount--;
    writeSavedLocations();
}

