// Case-insensitive substring search, written by hand rather than relying on
// strcasestr (not guaranteed available in the devkitPro newlib build).
static int containsCaseInsensitive(const char *haystack, const char *needle) {
    if (!*needle) return 1;
    size_t hl = strlen(haystack), nl = strlen(needle);
    for (size_t i = 0; i + nl <= hl; i++) {
        size_t j = 0;
        for (; j < nl; j++) {
            if (tolower((unsigned char)haystack[i + j]) != tolower((unsigned char)needle[j])) break;
        }
        if (j == nl) return 1;
    }
    return 0;
}

static int buildFilteredCities(const CityEntry **sortedCities, const char *filter,
                                const CityEntry **outFiltered) {
    if (!filter || !filter[0]) {
        memcpy(outFiltered, sortedCities, sizeof(CityEntry *) * CITY_COUNT);
        return CITY_COUNT;
    }
    int n = 0;
    for (int i = 0; i < CITY_COUNT; i++) {
        if (containsCaseInsensitive(sortedCities[i]->label, filter)) outFiltered[n++] = sortedCities[i];
    }
    return n;
}

